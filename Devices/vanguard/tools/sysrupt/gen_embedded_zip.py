"""Generate the embedded toolkit-ZIP C asset served at /toolkit.zip by the firmware.

Mirrors the project's existing embedded-asset convention (see source/ot/net/ReactorImg.cpp): a
committed C source file holding the bytes as `const unsigned char toolkit_zip[]` plus its length.
Run from tools/sysrupt/ after rebuilding release/*.zip:

    python3 gen_embedded_zip.py release/sysrupt-toolkit-1.0.0.zip

It writes source/ot/net/ToolkitZip.{h,cpp} (paths resolved relative to this script's repo).
The emitted file also records the SHA-256 so the firmware and tests can assert integrity.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NET = os.path.normpath(os.path.join(HERE, "..", "..", "source", "ot", "net"))


def main():
    zip_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "release",
                                                                   "sysrupt-toolkit-1.0.0.zip")
    with open(zip_path, "rb") as fh:
        data = fh.read()
    sha = hashlib.sha256(data).hexdigest()
    name = os.path.basename(zip_path)

    with open(os.path.join(NET, "ToolkitZip.h"), "w") as h:
        h.write(
            "// SPDX-License-Identifier: Apache-2.0\n"
            "#pragma once\n"
            "// Embedded SYSRUPT player-toolkit release archive, served at /toolkit.zip by OtHttp\n"
            "// (engineer-session gated). GENERATED by tools/sysrupt/gen_embedded_zip.py -- do not edit.\n"
            "extern const unsigned char toolkit_zip[];\n"
            "extern const unsigned int toolkit_zip_len;\n"
            "extern const char toolkit_zip_sha256[];\n"
            "extern const char toolkit_zip_name[];\n")

    with open(os.path.join(NET, "ToolkitZip.cpp"), "w") as c:
        c.write("// SPDX-License-Identifier: Apache-2.0\n")
        c.write(f"// GENERATED from {name} ({len(data)} bytes, sha256 {sha}).\n")
        c.write("// Regenerate with tools/sysrupt/gen_embedded_zip.py -- do not edit by hand.\n")
        c.write('#include "ToolkitZip.h"\n')
        c.write("const unsigned char toolkit_zip[] = {\n")
        for i in range(0, len(data), 12):
            row = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
            c.write(f"  {row},\n")
        c.write("};\n")
        c.write(f"const unsigned int toolkit_zip_len = {len(data)};\n")
        c.write(f'const char toolkit_zip_sha256[] = "{sha}";\n')
        c.write(f'const char toolkit_zip_name[] = "{name}";\n')

    print(f"embedded {len(data)} bytes (sha256 {sha}) -> {NET}/ToolkitZip.cpp")


if __name__ == "__main__":
    main()
